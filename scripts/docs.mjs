function whatsNewPayload(md, version) {
  let heading = version;
  let notes = changelogBullets(md, version);
  if (notes.length === 0) {
    heading = 'Unreleased';
    notes = changelogBullets(md, 'Unreleased');
  }

  return `${JSON.stringify({ version, heading, notes }, null, 2)}\n`;
}

function checkVersionDrift(version, bundled) {
  const tauri = JSON.parse(
    readFileSync(join(root, 'desktop/src-tauri/tauri.conf.json'), 'utf8'),
  ).version;
  const pkg = JSON.parse(readFileSync(join(root, 'desktop/package.json'), 'utf8')).version;
  const cargoMatch = /^version = "([^"]+)"/m.exec(
    readFileSync(join(root, 'desktop/src-tauri/Cargo.toml'), 'utf8'),
  );
  const cargo = cargoMatch ? cargoMatch[1] : '';
  for (const [name, got] of Object.entries({
    'tauri.conf.json': tauri,
    'desktop/package.json': pkg,
    'Cargo.toml': cargo,
    'whats-new.json': bundled,
  })) {
    if (got !== version) {
      process.stderr.write(`version drift: ${name} is ${got}, Go is ${version}\n`);
      return true;
    }
  }

  return false;
}

const go = goTests();
const rust = rustTests();
const catalog = loadCatalog();
const changelogMd = readFileSync(join(root, 'CHANGELOG.md'), 'utf8');
const version = appVersion();
const featuresMd = featuresMarkdown(go, rust);
const seamsMd = seamsMarkdown(go, rust);
const assetsMd = assetsMarkdown(catalog);
const files = {
  'docs/features.md': featuresMd,
  'docs/seams.md': seamsMd,
  'docs/assets.md': assetsMd,
  'site/changelog.html': changelogPage(changelogMd),
  'site/docs/index.html': docsHubPage(),
  'site/docs/features.html': markdownSitePage({
    title: 'Sopsdeck — features',
    kicker: 'Living spec',
    heading: 'Features proved by tests',
    lede: 'Generated from test names. If a behavior is not named here, it is not specified by a test yet.',
    md: featuresMd,
  }),
  'site/docs/seams.html': markdownSitePage({
    title: 'Sopsdeck — seams',
    kicker: 'Delivery',
    heading: 'Public seams',
    lede: 'Where tests must live, and which delivery phases still have none.',
    md: seamsMd,
  }),
  'site/docs/assets.html': markdownSitePage({
    title: 'Sopsdeck — assets',
    kicker: 'Catalog',
    heading: 'Product assets',
    lede: 'Stills, clips, walkthrough, and CLI casts from <code>./scripts/demo</code>.',
    md: assetsMd,
  }),
  'site/docs/versioning.html': markdownSitePage({
    title: 'Sopsdeck — versioning',
    kicker: 'Releases',
    heading: 'Versioning',
    lede: 'Epoch SemVer. CHANGELOG.md is the source of truth.',
    md: readFileSync(join(root, 'docs/versioning.md'), 'utf8'),
  }),
  'site/docs/glossary.html': markdownSitePage({
    title: 'Sopsdeck — domain language',
    kicker: 'Glossary',
    heading: 'Domain language',
    lede: 'Words from CONTEXT.md. Use these in tests, UI copy, and docs.',
    md: readFileSync(join(root, 'CONTEXT.md'), 'utf8'),
  }),
  'desktop/src/whats-new.json': whatsNewPayload(changelogMd, version),
};

let stale = false;
for (const [rel, body] of Object.entries(files)) {
  const path = join(root, rel);
  if (check) {
    let current = '';
    try {
      current = readFileSync(path, 'utf8');
    } catch {
      current = '';
    }
    if (current !== body) {
      process.stderr.write(`${rel} is stale; run ./scripts/docs\n`);
      stale = true;
    }
    continue;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, body);
}

if (check) {
  for (const rel of requiredAssetFiles(catalog)) {
    if (!existsSync(join(root, rel))) {
      process.stderr.write(`${rel} is missing; run ./scripts/demo\n`);
      stale = true;
    }
  }

  for (const name of unlinkedAssets(catalog)) {
    process.stderr.write(`${name} is not referenced in README, docs, or the landing page\n`);
    stale = true;
  }

  const bundled = JSON.parse(files['desktop/src/whats-new.json']).version;
  if (checkVersionDrift(version, bundled)) stale = true;

  if (checkClips) {
    for (const rel of clipAssetFiles(catalog)) {
      const path = join(root, rel);
      if (!existsSync(path)) {
        continue;
      }

      const seconds = mediaDurationSeconds(path);
      if (!Number.isFinite(seconds) || seconds < minClipSeconds) {
        process.stderr.write(
          `${rel} is ${Number.isFinite(seconds) ? `${seconds.toFixed(3)}s` : 'unreadable'}; want ≥ ${minClipSeconds}s. Re-record with ./scripts/demo\n`,
        );
        stale = true;
      }
    }
  }
}

function clipAssetFiles(catalog) {
  return [
    `docs/assets/${catalog.walkthrough}`,
    ...catalog.items.map((item) => `docs/assets/${item.clip}`),
    ...catalogCasts(catalog).map((item) => `docs/assets/${item.cast}`),
  ];
}

if (stale) {
  process.exit(1);
}
